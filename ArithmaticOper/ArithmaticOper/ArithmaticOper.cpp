

#include <iostream>
using namespace std;

int main()
{
	int A;
	int B;

	cout << "Please enter the first number A?" << endl;
	cin >> A;
	cout << "Please enter the second number b?" << endl;
	cin >> B;
	cout << endl;

	cout << A << " + " << B << " = " << A + B << endl;
	cout << A << " - " << B << " = " << A - B << endl;
	cout << A << " * " << B << " = " << A * B << endl;
	cout << A << " / " << B << " = " << A / B << endl;
	cout << A << " % " << B << " = " << A % B << endl;
}

